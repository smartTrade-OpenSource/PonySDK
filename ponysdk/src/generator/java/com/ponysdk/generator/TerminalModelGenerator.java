package com.ponysdk.generator;

import java.io.IOException;
import java.lang.reflect.Field;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

/**
 * Writes the protocol model of the TypeScript terminal (ADR-0002) from {@code com.ponysdk.core.model}, which stays the
 * single source of the protocol.
 * <ul>
 * <li>An enum becomes a {@code const} object from constant name to wire value: {@code getByteValue()}, else a numeric
 * {@code getValue()}, else {@code toStringValue()}, else its own {@code toString()}, else the ordinal. A numeric enum
 * also gets {@code <Enum>Names}, its names by value.</li>
 * <li>Each other public getter of an enum becomes {@code <Enum><Property>}: an array by value for a numeric enum, an
 * object by name otherwise. An enum result is written as its wire value.</li>
 * <li>Public static final constants become {@code <Class>Constants}, or {@code <Class>} for a class that holds only
 * constants.</li>
 * <li>A public static method from one model enum to another becomes {@code <From>To<To>}, null where it throws.</li>
 * </ul>
 * Arguments: the output file, then the directory of the compiled main classes.
 */
public final class TerminalModelGenerator {

    private static final String PACKAGE = "com.ponysdk.core.model";

    private TerminalModelGenerator() {
    }

    public static void main(final String[] args) throws Exception {
        final Path output = Path.of(args[0]);
        final StringBuilder ts = new StringBuilder("// Generated by ").append(TerminalModelGenerator.class.getName())
            .append(" from ").append(PACKAGE).append(". Do not edit.\n");
        for (final Class<?> type : modelClasses(Path.of(args[1]))) {
            if (type.isEnum()) writeEnum(ts, type);
            else writeClass(ts, type);
        }
        Files.createDirectories(output.getParent());
        Files.writeString(output, ts);
    }

    private static List<Class<?>> modelClasses(final Path classes) throws IOException, ClassNotFoundException {
        final Path dir = classes.resolve(PACKAGE.replace('.', '/'));
        final List<String> names;
        try (Stream<Path> files = Files.list(dir)) {
            names = files.map(f -> f.getFileName().toString())
                .filter(n -> n.endsWith(".class") && !n.contains("$") && !n.contains("-"))
                .map(n -> n.substring(0, n.length() - ".class".length()))
                .sorted()
                .toList();
        }
        final List<Class<?>> types = new ArrayList<>();
        for (final String name : names) {
            final Class<?> type = Class.forName(PACKAGE + "." + name);
            if (Modifier.isPublic(type.getModifiers())) types.add(type);
        }
        return types;
    }

    private static void writeEnum(final StringBuilder ts, final Class<?> type) throws ReflectiveOperationException {
        final String name = type.getSimpleName();
        final Method primary = primary(type);
        final Object[] constants = type.getEnumConstants();
        final Map<String, Object> values = new LinkedHashMap<>();
        for (final Object constant : constants) values.put(((Enum<?>) constant).name(), wireValue(constant));
        final boolean numeric = values.values().stream().allMatch(v -> v instanceof Number);

        ts.append("\nexport const ").append(name).append(" = {\n");
        values.forEach((k, v) -> ts.append("    ").append(k).append(": ").append(literal(v)).append(",\n"));
        ts.append("} as const;\n");
        ts.append("export type ").append(name).append(" = (typeof ").append(name).append(")[keyof typeof ").append(name)
            .append("];\n");
        if (numeric) {
            final Map<Object, Object> names = new LinkedHashMap<>();
            values.forEach((k, v) -> names.put(v, k));
            writeTable(ts, name + "Names", names, "string");
        }

        for (final Method getter : getters(type)) {
            if (getter.equals(primary)) continue;
            final Map<Object, Object> table = new LinkedHashMap<>();
            for (final Object constant : constants) {
                final Object result = getter.invoke(constant);
                table.put(numeric ? wireValue(constant) : ((Enum<?>) constant).name(), result instanceof Enum<?> ? wireValue(result) : result);
            }
            final String tableName = name + property(getter.getName());
            if (numeric) writeTable(ts, tableName, table, tsType(getter.getReturnType()));
            else writeObject(ts, tableName, table);
        }

        writeConstants(ts, name + "Constants", type);
    }

    private static void writeClass(final StringBuilder ts, final Class<?> type) throws ReflectiveOperationException {
        writeConstants(ts, type.getSimpleName(), type);
        for (final Method converter : Arrays.stream(type.getDeclaredMethods()).sorted(Comparator.comparing(Method::toString)).toList()) {
            final int modifiers = converter.getModifiers();
            if (!Modifier.isPublic(modifiers) || !Modifier.isStatic(modifiers) || converter.getParameterCount() != 1) continue;
            final Class<?> from = converter.getParameterTypes()[0];
            final Class<?> to = converter.getReturnType();
            if (!isModelEnum(from) || !isModelEnum(to)) continue;
            final Map<Object, Object> table = new LinkedHashMap<>();
            for (final Object constant : from.getEnumConstants()) {
                Object result;
                try {
                    result = wireValue(converter.invoke(null, constant));
                } catch (final InvocationTargetException e) {
                    result = null;
                }
                table.put(wireValue(constant), result);
            }
            writeTable(ts, from.getSimpleName() + "To" + to.getSimpleName(), table, "number");
        }
    }

    private static void writeConstants(final StringBuilder ts, final String name, final Class<?> type) throws IllegalAccessException {
        final Map<String, Object> constants = new LinkedHashMap<>();
        for (final Field field : type.getDeclaredFields()) {
            final int modifiers = field.getModifiers();
            if (field.isEnumConstant() || field.isSynthetic() || !Modifier.isPublic(modifiers) || !Modifier.isStatic(modifiers)
                    || !Modifier.isFinal(modifiers)) continue;
            if (field.getType().isPrimitive() || field.getType() == String.class) constants.put(field.getName(), field.get(null));
        }
        if (constants.isEmpty()) return;
        ts.append("\nexport const ").append(name).append(" = {\n");
        constants.forEach((k, v) -> ts.append("    ").append(k).append(": ").append(literal(v)).append(",\n"));
        ts.append("} as const;\n");
    }

    /** An array indexed by key, null in the gaps: keys are small wire values, read on the hot path. */
    private static void writeTable(final StringBuilder ts, final String name, final Map<Object, Object> table, final String type) {
        final int size = table.keySet().stream().mapToInt(k -> ((Number) k).intValue()).max().orElse(-1) + 1;
        final Object[] slots = new Object[size];
        table.forEach((k, v) -> slots[((Number) k).intValue()] = v);
        final boolean nullable = Arrays.stream(slots).anyMatch(v -> v == null);
        ts.append("export const ").append(name).append(": readonly ").append(nullable ? "(" + type + " | null)" : type)
            .append("[] = [");
        for (int i = 0; i < size; i++) ts.append(i == 0 ? "" : ", ").append(literal(slots[i]));
        ts.append("];\n");
    }

    private static void writeObject(final StringBuilder ts, final String name, final Map<Object, Object> table) {
        ts.append("export const ").append(name).append(" = {\n");
        table.forEach((k, v) -> ts.append("    ").append(k).append(": ").append(literal(v)).append(",\n"));
        ts.append("} as const;\n");
    }

    /** The method giving the value the protocol carries; null for the ordinal. */
    private static Method primary(final Class<?> type) {
        for (final String candidate : List.of("getByteValue", "getValue", "toStringValue", "toString")) {
            try {
                final Method method = type.getDeclaredMethod(candidate);
                final Class<?> result = method.getReturnType();
                if (candidate.equals("getValue") && !isNumber(result)) continue;
                if (Modifier.isPublic(method.getModifiers()) && !Modifier.isStatic(method.getModifiers())) return method;
            } catch (final NoSuchMethodException e) {
                // next candidate
            }
        }
        return null;
    }

    private static Object wireValue(final Object constant) throws ReflectiveOperationException {
        if (constant == null) return null;
        final Enum<?> value = (Enum<?>) constant;
        final Method primary = primary(value.getDeclaringClass());
        return primary == null ? value.ordinal() : primary.invoke(value);
    }

    private static List<Method> getters(final Class<?> type) {
        return Arrays.stream(type.getDeclaredMethods())
            .filter(m -> Modifier.isPublic(m.getModifiers()) && !Modifier.isStatic(m.getModifiers()) && !m.isSynthetic())
            .filter(m -> m.getParameterCount() == 0 && !m.getName().equals("toString"))
            .filter(m -> isNumber(m.getReturnType()) || m.getReturnType() == boolean.class || m.getReturnType() == String.class
                    || isModelEnum(m.getReturnType()))
            .sorted(Comparator.comparing(Method::getName))
            .toList();
    }

    private static String property(final String getter) {
        for (final String prefix : List.of("get", "is", "to")) {
            if (getter.startsWith(prefix) && getter.length() > prefix.length() && Character.isUpperCase(getter.charAt(prefix.length())))
                return getter.substring(prefix.length());
        }
        return Character.toUpperCase(getter.charAt(0)) + getter.substring(1);
    }

    private static String tsType(final Class<?> type) {
        if (type == boolean.class) return "boolean";
        if (type == String.class) return "string";
        return "number";
    }

    private static boolean isNumber(final Class<?> type) {
        return type == byte.class || type == short.class || type == int.class || type == long.class || type == double.class
                || type == float.class;
    }

    private static boolean isModelEnum(final Class<?> type) {
        return type.isEnum() && type.getPackageName().equals(PACKAGE);
    }

    private static String literal(final Object value) {
        if (value == null) return "null";
        if (value instanceof Number || value instanceof Boolean) return value.toString();
        final StringBuilder s = new StringBuilder("\"");
        for (final char c : value.toString().toCharArray()) {
            if (c == '"' || c == '\\') s.append('\\').append(c);
            else if (c < 0x20) s.append(String.format("\\u%04x", (int) c));
            else s.append(c);
        }
        return s.append('"').toString();
    }
}
